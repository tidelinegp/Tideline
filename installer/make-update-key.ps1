<#
Creates the key pair that signs Tideline updates. Run it ONCE.
  - The private key stays on this PC (outside the repository) and is the only thing that can publish updates.
  - The public half is written to update-public.txt and compiled into the launcher (src\browser\update_key.h).
Back up the private key somewhere safe (password manager, USB stick). If it is lost, installed copies can never
verify a new update again and everyone would have to reinstall by hand. Never commit or share it.
#>
$ErrorActionPreference = "Stop"
$dir = Join-Path $env:USERPROFILE ".tideline-signing"
$priv = Join-Path $dir "update-private.pk8"
if (Test-Path $priv) { throw "A key already exists at $priv. Delete it only if you really mean to replace it (old installs would stop accepting updates)." }
New-Item -ItemType Directory $dir -Force | Out-Null
$ec = [System.Security.Cryptography.ECDsa]::Create([System.Security.Cryptography.ECCurve]::CreateFromFriendlyName("nistP256"))
[IO.File]::WriteAllBytes($priv, $ec.ExportPkcs8PrivateKey())
$p = $ec.ExportParameters($false)
$hex = ([BitConverter]::ToString($p.Q.X) + [BitConverter]::ToString($p.Q.Y)).Replace("-", "").ToLower()
Set-Content (Join-Path $PSScriptRoot "update-public.txt") $hex -NoNewline
$bytes = ($hex -split '(?<=\G.{2})' | Where-Object { $_ } | ForEach-Object { "0x$_" }) -join ", "
$hdr = "// Public key that update signatures are checked against. Generated by installer\make-update-key.ps1.`n// ECDSA P-256: 32 bytes X then 32 bytes Y.`nstatic const unsigned char UPDATE_PUBLIC_KEY[64] = { $bytes };`n"
Set-Content (Join-Path $PSScriptRoot "..\src\browser\update_key.h") $hdr
Write-Host "Private key: $priv (BACK THIS UP)`nPublic key written to update-public.txt and src\browser\update_key.h"
